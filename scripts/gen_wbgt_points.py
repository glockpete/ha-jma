"""Regenerate custom_components/jma/wbgt_points.py from the Ministry of the Environment's point master.

The master is the ministry's own CSV, linked from https://www.wbgt.env.go.jp/data_service.php (情報提供地点マスタ):

    https://www.wbgt.env.go.jp/man15NH/wbgt_point_master-<yyyymmdd>.csv

A copy is kept as tests/fixtures/wbgt_point_master.csv; tests/test_wbgt_points.py renders it again and fails when the
shipped module differs, so the table cannot drift from its source. To follow a new master:

    python scripts/gen_wbgt_points.py tests/fixtures/wbgt_point_master.csv wbgt_point_master-<yyyymmdd>.csv \
        > custom_components/jma/wbgt_points.py

Standard library only; it reads the prefecture tables out of const.py without importing Home Assistant.
"""

from __future__ import annotations

import csv
import importlib.util
import io
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = "wbgt_point_master-20260515.csv"
# Master columns: 地方, 振興局, 地点番号, 観測所名, よみがな, ローマ字表記, 所在地, Latitude (deg), Latitude_3 (min),
# Longitude (deg), Longitude_4 (min), start date, end date, ...
_COL_REGION, _COL_AREA, _COL_ID, _COL_NAME = 0, 1, 2, 3
_COL_LAT_DEG, _COL_LAT_MIN, _COL_LON_DEG, _COL_LON_MIN, _COL_END = 7, 8, 9, 10, 12
_STILL_RUNNING = "9999-99-99"  # the end date of a point that is in service
_HOKKAIDO = "北海道"  # the region column of every Hokkaido point; its 振興局 column holds the sub-prefecture


def load_const() -> tuple[dict[str, str], dict[str, str]]:
    """(PREFECTURES, WBGT_PREF_FILE) from const.py, read as a plain module."""
    spec = importlib.util.spec_from_file_location("jma_const_for_gen", ROOT / "custom_components" / "jma" / "const.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module  # dataclasses and typing look the module up by name
    spec.loader.exec_module(module)
    return dict(module.PREFECTURES), dict(module.WBGT_PREF_FILE)


def _short(prefecture: str) -> str:
    return prefecture[:-1] if prefecture[-1:] in ("都", "府", "県") else prefecture


def points_by_file(master_text: str, prefectures: dict[str, str], pref_file: dict[str, str]
                   ) -> dict[str, list[tuple[str, str, float, float]]]:
    """The points in service, grouped by prefecture file: (point number, name, latitude, longitude)."""
    by_code = {_short(name): code for code, name in prefectures.items()}
    out: dict[str, list[tuple[str, str, float, float]]] = {name: [] for name in pref_file.values()}
    rows = list(csv.reader(io.StringIO(master_text.lstrip("\ufeff"))))
    for row in rows[1:]:
        cells = [c.strip() for c in row]
        if len(cells) <= _COL_END or cells[_COL_END] != _STILL_RUNNING:
            continue
        code = "01" if cells[_COL_REGION] == _HOKKAIDO else by_code[cells[_COL_AREA]]
        lat = round(float(cells[_COL_LAT_DEG]) + float(cells[_COL_LAT_MIN]) / 60, 4)
        lon = round(float(cells[_COL_LON_DEG]) + float(cells[_COL_LON_MIN]) / 60, 4)
        out[pref_file[code]].append((cells[_COL_ID], cells[_COL_NAME], lat, lon))
    return {name: sorted(points) for name, points in out.items()}


def render(master_text: str, prefectures: dict[str, str], pref_file: dict[str, str], source: str = DEFAULT_SOURCE) -> str:
    grouped = points_by_file(master_text, prefectures, pref_file)
    total = sum(len(points) for points in grouped.values())
    lines = [
        '"""環境省 WBGT points (暑さ指数の情報提供地点): number, name and position of every point the Ministry forecasts.',
        "",
        f"GENERATED by scripts/gen_wbgt_points.py from the Ministry's point master {source} ({total} points in",
        "service, 運用中). Do not edit by hand; tests/test_wbgt_points.py renders the master again and compares.",
        "https://www.wbgt.env.go.jp/data_service.php. The point numbers are the AMeDAS station numbers and are the row",
        "keys of the yohou_<prefecture>.csv files. Positions are the master's degrees and minutes, in decimal degrees.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Final",
        "",
        "# prefecture file name (const.WBGT_PREF_FILE) -> ((point number, name, latitude, longitude), ...) by number",
        "WBGT_POINTS: Final[dict[str, tuple[tuple[str, str, float, float], ...]]] = {",
    ]
    for name in pref_file.values():
        lines.append(f'    "{name}": (')
        for number, point, lat, lon in grouped[name]:
            lines.append(f'        ("{number}", {json.dumps(point, ensure_ascii=False)}, {lat!r}, {lon!r}),')
        lines.append("    ),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) not in (2, 3):
        print(__doc__, file=sys.stderr)
        return 2
    prefectures, pref_file = load_const()
    text = Path(argv[1]).read_text(encoding="utf-8")
    # Bytes, so the file is UTF-8 with LF whatever the console's encoding and line endings are.
    sys.stdout.buffer.write(
        render(text, prefectures, pref_file, argv[2] if len(argv) == 3 else DEFAULT_SOURCE).encode("utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
