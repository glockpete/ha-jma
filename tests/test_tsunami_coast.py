"""The tsunami coast table: for each coastal municipality, the 津波予報区 (tsunami forecast regions) JMA gives it.

`custom_components/jma/tsunami_coast_data.py` is generated by `scripts/build_tsunami_coast.py` from JMA's own list,
"津波予報区に対応する沿岸の市町村対応表" (https://www.jma.go.jp/jma/kishou/know/jishin/joho/tsunami-yohoku/tsunami_shichouson.pdf,
as of 令和8年3月26日, fetched 2026-10-24). The text of the table of that PDF is the fixture
`tsunami_shichouson_rows.json`; the class20 codes are those of `area.json`. The tests make the table again from the two
and compare it with the module, check it against what the tsunami information itself writes (the names of the areas
in P2P's list and in JMA's own file) and pin the rules that turn a name of the PDF into class20 codes.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path
from types import ModuleType

import pytest

from custom_components.jma import tsunami_coast_data
from custom_components.jma.config_flow import area_chain
from custom_components.jma.const import TSUNAMI_COAST_AREA
from custom_components.jma.tsunami_coast import home_regions
from custom_components.jma.tsunami_coast_data import TSUNAMI_COAST

from .helpers import load_json

ROOT = Path(__file__).resolve().parent.parent
ROWS = load_json("tsunami_shichouson_rows.json")
AREA = load_json("area.json")
CLASS20 = AREA["class20s"]
HISTORY = load_json("p2p_jma_tsunami_history.json")
JMA_FEED = load_json("jma_tsunami_VTSE41_20261010.json")


def _script() -> ModuleType:
    spec = importlib.util.spec_from_file_location("build_tsunami_coast", ROOT / "scripts" / "build_tsunami_coast.py")
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


SCRIPT = _script()
REGIONS = {row[0] for row in ROWS["rows"]}


def _prefecture(code: str) -> dict[str, str]:
    return {c: row["name"] for c, row in CLASS20.items() if c[:2] == code}


# ---------------------------------------------------------------- the module is what the script makes of JMA's list

def test_the_module_is_what_the_script_makes_of_the_saved_rows() -> None:
    table = SCRIPT.resolve(ROWS["rows"], CLASS20)
    assert table == TSUNAMI_COAST
    text = SCRIPT.render(table, {**ROWS, "area_url": SCRIPT.AREA_URL})
    assert text == Path(tsunami_coast_data.__file__).read_text(encoding="utf-8")


def test_the_saved_rows_say_where_they_come_from() -> None:
    assert ROWS["source_url"] == SCRIPT.PDF_URL
    assert ROWS["http_status"] == 200
    assert ROWS["as_of"] == "令和8年3月26日時点"
    assert (ROWS["fetched"], len(ROWS["sha256"])) == ("2026-10-24", 64)
    assert len(ROWS["rows"]) == 82 and all(len(row) == 3 and all(row) for row in ROWS["rows"])


def test_the_script_checks_and_writes_the_module(monkeypatch: pytest.MonkeyPatch, tmp_path: Path,
                                                 capsys: pytest.CaptureFixture[str]) -> None:
    rows, area = str(ROOT / "tests" / "fixtures" / "tsunami_shichouson_rows.json"), str(ROOT / "tests" / "fixtures" / "area.json")
    module = tmp_path / "tsunami_coast_data.py"
    monkeypatch.setattr(SCRIPT, "MODULE", module)
    monkeypatch.setattr(sys, "argv", ["build", "--rows", rows, "--area", area, "--write", "--check"])
    assert SCRIPT.main() == 0
    assert module.read_text(encoding="utf-8") == Path(tsunami_coast_data.__file__).read_text(encoding="utf-8")
    assert f"({len(TSUNAMI_COAST)} areas)" in capsys.readouterr().out
    module.write_text("TSUNAMI_COAST = {}\n", encoding="utf-8")
    monkeypatch.setattr(sys, "argv", ["build", "--rows", rows, "--area", area, "--check"])
    assert SCRIPT.main() == 1
    assert "differs" in capsys.readouterr().err


# ---------------------------------------------------------------- against the names the tsunami information writes

def test_the_regions_are_the_66_areas_of_jma_and_the_names_both_feeds_write() -> None:
    regions = {name for names in TSUNAMI_COAST.values() for name in names}
    assert regions == REGIONS and len(regions) == 66
    p2p = {a["name"] for message in HISTORY for a in message["areas"]}
    jma = {item["Area"]["Name"] for item in JMA_FEED["Body"]["Tsunami"]["Forecast"]["Item"]}
    assert p2p <= regions and len(p2p) == 60  # 72 bulletins of P2P's list, 2016 to 2026
    assert jma <= regions and len(jma) == 28  # JMA's own file of 2026-10-10 (津波予報, 若干の海面変動)


def test_the_table_only_has_class20_codes_of_the_area_list() -> None:
    assert set(TSUNAMI_COAST) <= set(CLASS20)
    assert all(names and len(set(names)) == len(names) for names in TSUNAMI_COAST.values())


def test_a_prefecture_without_a_coast_has_no_entry() -> None:
    inland = {"09": "栃木県", "10": "群馬県", "11": "埼玉県", "19": "山梨県", "20": "長野県", "21": "岐阜県",
              "25": "滋賀県", "29": "奈良県"}
    for number in inland:
        assert _prefecture(number), inland[number]
        assert not [code for code in TSUNAMI_COAST if code[:2] == number], inland[number]


def test_every_other_prefecture_has_a_coast() -> None:
    inland = {"09", "10", "11", "19", "20", "21", "25", "29"}
    for number in sorted({code[:2] for code in CLASS20} - inland):
        assert [code for code in TSUNAMI_COAST if code[:2] == number], number


