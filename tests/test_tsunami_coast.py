# ---------------------------------------------------------------- which regions an entry follows

def test_home_regions_come_from_the_municipality_first() -> None:
    assert home_regions("1420100", "140013") == ("東京湾内湾", "相模湾・三浦半島")
    assert home_regions("1310300", "130010") == ("東京湾内湾",)
    assert home_regions("1340100", "130030") == ("伊豆諸島",)
    assert home_regions("2710000", "270001") == ("大阪府",)


def test_a_tokyo_place_that_is_not_on_the_list_keeps_the_tokyo_class10_region() -> None:
    assert home_regions("1310100", "130010") == ("東京湾内湾",)    # 千代田区
    assert home_regions("1320900", "130010") == ("東京湾内湾",)    # 町田市
    assert home_regions("1310100", "130020") == ("伊豆諸島",)      # the class10 table is kept as it was
    assert home_regions("1310100", "130040") == ("小笠原諸島",)


def test_an_inland_place_has_no_region() -> None:
    class10, _ = area_chain(AREA, "2020300")  # 上田市
    assert home_regions("2020300", class10) == ()
    assert home_regions("0110000", "016012") == ()
    assert home_regions("1310100", "999999") == ()


def test_every_tokyo_municipality_has_a_region_and_the_others_have_one_only_on_the_list() -> None:
    for code, row in CLASS20.items():
        class15 = AREA["class15s"].get(row["parent"])
        if class15 is None:
            continue  # a class20 area that no class15 area lists: the config flow cannot offer it
        class10 = class15["parent"]
        office = AREA["class10s"][class10]["parent"]
        regions = home_regions(code, class10)
        if office == "130000":
            assert regions, (code, row["name"])
        else:
            assert bool(regions) == (code in TSUNAMI_COAST), (code, row["name"])
    assert set(TSUNAMI_COAST_AREA.values()) <= REGIONS


# ---------------------------------------------------------------- the rules that turn a name of the PDF into codes

def test_a_name_that_is_an_area_or_a_municipality_split_into_parts() -> None:
    hokkaido = _prefecture("01")
    assert SCRIPT.resolve_name("函館市", hokkaido) == ["0120200"]
    assert SCRIPT.resolve_name("釧路市", hokkaido) == ["0120601", "0120602", "0120603"]
    assert SCRIPT.resolve_name("八雲町八雲", hokkaido) == ["0134601"]
    assert SCRIPT.resolve_name("八雲町", hokkaido) == ["0134601", "0134602"]


def test_a_name_that_starts_the_names_of_the_wards_of_a_city() -> None:
    wards = SCRIPT.resolve_name("神戸市", _prefecture("28"))
    assert len(wards) == 9 and all(CLASS20[code]["name"].startswith("神戸市") for code in wards)


