def test_a_name_that_fits_nothing_or_two_names_is_refused() -> None:
    with pytest.raises(SCRIPT.ResolveError, match="no class20 area for '存在しない村'"):
        SCRIPT.resolve_name("存在しない村", _prefecture("01"))
    with pytest.raises(SCRIPT.ResolveError, match="fits several"):
        SCRIPT.resolve_name("あい市いう市", {"0100100": "あい市", "0100200": "いう市"})


def test_notes_and_the_northern_territories() -> None:
    assert SCRIPT.split_cell("松前町（白神岬の東）、 八雲町八雲、") == ["松前町", "八雲町八雲"]
    assert SCRIPT.prefecture_of("北海道（釧路地方）") == "北海道"
    assert SCRIPT.prefecture_of("沖縄県") == "沖縄県"
    with pytest.raises(SCRIPT.ResolveError, match="prefecture not recognised"):
        SCRIPT.prefecture_of("月（地方）")
    rows = [["北海道太平洋沿岸東部", "北海道（根室地方）", "根室市、色丹村、国後泊村、紗那村"]]
    # the villages of the Northern Territories have no class20 area and are left out; 国後泊村 is not read as 泊村
    assert SCRIPT.resolve(rows, CLASS20) == {"0122300": ("北海道太平洋沿岸東部",)}  # 根室市
    assert SCRIPT.NORTHERN_TERRITORIES == {"色丹村", "国後泊村", "留夜別村", "留別村", "紗那村", "蘂取村"}
